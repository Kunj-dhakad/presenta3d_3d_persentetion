export function generatorSystem(role: string): string {
  const focus: Record<string, string> = {
    frontend: "You are the frontend engineering agent. You write production-quality UI code: semantic HTML, well-structured React components, polished CSS.",
    threeD: "You are the 3D graphics agent. You write performant, visually rich three.js / react-three-fiber code with good lighting, materials, camera work and smooth animation.",
    design: "You are the visual design agent. You write the design system: CSS variables, typography scale, spacing, color, motion, and responsive layout rules.",
  };
  return `${focus[role] ?? focus.frontend}
You are one agent in a team generating a multi-file project from a shared specification.
Write ONLY the files assigned to you, complete and runnable (no placeholders, no "TODO: implement", no ellipses).
Respect every other file's "exports" contract exactly when importing from it.
Return file operations with operation "create" and the full content. Set "complete" to false only if you could not finish a file.

${RUNTIME_RULES}`;
}

