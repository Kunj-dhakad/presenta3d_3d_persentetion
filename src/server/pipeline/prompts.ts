export function specSummary(spec: ProjectSpec): string {
  return [
    `Title: ${spec.title}`,
    `Goal: ${spec.goal}`,
    `Category: ${spec.category}; framework: ${spec.framework}`,
    `Design system: palette ${spec.designSystem.palette.join(", ")}; typography ${spec.designSystem.typography}; style ${spec.designSystem.style}`,
    `Components: ${spec.components.join(", ")}`,
    `Interactions: ${spec.interactions.join("; ")}`,
    `Responsive: ${spec.responsive}`,
    `Packages: ${spec.packages.join(", ") || "(none)"}`,
    `Acceptance tests: ${spec.acceptanceTests.join("; ")}`,
    "Files:",
    ...spec.files.map((f) => `- ${f.path} [group ${f.group}] — ${f.purpose}. Exports/contract: ${f.exports || "(none)"}`),
  ].join("\n");
}

