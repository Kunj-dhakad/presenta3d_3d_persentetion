/** Deck fixture: a new sample deck, or an edit that renames a slide title given in quotes. */
function mockDeck(input: string, request: string): DeckSpec {
  const current = /Current deck \(JSON\):\n(.+)/.exec(input)?.[1];
  if (current) {
    const deck = JSON.parse(current) as DeckSpec;
    const quoted = /["“]([^"”]{1,80})["”]/.exec(request)?.[1];
    const n = Number(/slide\s+(\d+)/i.exec(request)?.[1] ?? "1");
    const slide = deck.slides[Math.min(deck.slides.length, Math.max(1, n)) - 1];
    if (quoted && slide) slide.title = quoted;
    return deck;
  }
  const topic = request.replace(/\s+/g, " ").split(/[.!\n]/)[0].slice(0, 40) || "Strata";
  return sampleDeck(topic);
}

/**
 * Deterministic offline provider used ONLY by automated tests (AI_PROVIDER=mock).
 * It returns schema-valid outputs derived from the request so the full
 * pipeline (planning → generation → validation → build → repair → edit) can
 * be exercised end-to-end without network access or an API key. It is
 * refused in production by env() and labelled in the UI.
 *
 * Special markers in prompts (tests only):
 *   [simulate-build-error]  first generation imports a package that is not allowed → exercises repair
 */
export class MockTextProvider implements TextModelProvider {
  readonly name = "mock";
  readonly model = "mock-deterministic";

  async structured<T extends z.ZodType>(req: StructuredRequest<T>): Promise<StructuredResult<z.infer<T>>> {
    const started = Date.now();
    if (req.signal?.aborted) throw new AIError("CANCELLED", "Request cancelled");
    await new Promise((r) => setTimeout(r, 30));
    const raw = respond(req.schemaName, req.input);
    req.onProgress?.(JSON.stringify(raw).length);
    const parsed = req.schema.safeParse(raw);
    const usage: Usage = { provider: this.name, model: this.model, requestId: `mock_${Date.now().toString(36)}`, inputTokens: Math.ceil(req.input.length / 4), outputTokens: Math.ceil(JSON.stringify(raw).length / 4), totalTokens: null, latencyMs: Date.now() - started, estimatedCostUsd: null };
    usage.totalTokens = (usage.inputTokens ?? 0) + (usage.outputTokens ?? 0);
    if (!parsed.success) {
      await recordUsage({ userId: req.userId, jobId: req.jobId, operation: req.operation, usage, success: false, errorCode: "INVALID_OUTPUT" });
      throw new AIError("INVALID_OUTPUT", `mock output invalid for ${req.schemaName}: ${parsed.error.issues[0]?.message}`);
    }
    await recordUsage({ userId: req.userId, jobId: req.jobId, operation: req.operation, usage, success: true });
    return { data: parsed.data, usage };
  }
}

function userRequest(input: string): string {
  const m = /User request:\n([\s\S]*?)(\n\n|$)/.exec(input);
  return (m?.[1] ?? input).trim();
}

function assigned(input: string): string[] {
  const m = /ASSIGNED_FILES: (.+)/.exec(input);
  return m ? m[1].split(",").map((s) => s.trim()).filter(Boolean) : [];
}

const is3d = (s: string) => /\b(3d|three|solar|planet|scene|orbit|galaxy|game)\b/i.test(s);

function op(path: string, content: string) {
  return { path, operation: "create" as const, content, patches: [], explanation: `Wrote ${path}` };
}

