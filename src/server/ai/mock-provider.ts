function respond(schemaName: string, input: string): unknown {
  const request = userRequest(input);
  switch (schemaName) {
    case "project_spec": {
      const three = is3d(request);
      return {
        understanding: `Build ${three ? "an interactive three.js scene" : "a small static website"} for: ${request.slice(0, 120)}`,
        title: request.split(/[.!\n]/)[0].slice(0, 50) || "Generated project",
        category: three ? "scene3d" : "website",
        framework: three ? "three" : "vanilla",
        goal: request.slice(0, 200),
        designSystem: { palette: ["#0b0b0f", "#ececf1", "#7c8cff"], typography: "system-ui", style: "minimal dark" },
        files: [
          { path: "index.html", purpose: "Document shell", exports: "#title, #counter, #scene/#app", group: "entry" },
          { path: three ? "style.css" : "styles.css", purpose: "Design system", exports: "CSS variables", group: "design" },
          { path: three ? "main.js" : "app.js", purpose: three ? "three.js scene" : "UI logic", exports: "none", group: "entry" },
        ],
        components: ["Hero", three ? "Scene" : "Steps"],
        packages: three ? ["three", "three/addons/controls/OrbitControls.js"] : [],
        interactions: ["Counter button"],
        responsive: "Fluid typography and full-width canvas",
        acceptanceTests: ["Title renders", "Counter increments"],
      };
    }
    case "file_operations": {
      const broken = /\[simulate-build-error\]/.test(input);
      return { operations: assigned(input).map((p) => op(p, fileContent(p, request, broken))), dependencies: [], validation: ["Open the preview"], complete: true };
    }
    case "edit_plan": {
      const wantsColor = /background|colou?r/i.test(request);
      return {
        understanding: `Apply the requested change: ${request.slice(0, 120)}`,
        summary: wantsColor ? "Update the background color in the stylesheet." : "Update the page heading.",
        targets: [wantsColor ? { path: /style\.css/.test(input) ? "style.css" : "styles.css", action: "modify", instructions: "Change --bg" } : { path: "index.html", action: "modify", instructions: "Change the h1 text" }],
        packages: [],
      };
    }
    case "edit_operations": {
      const files = assigned(input);
      const ops = files.map((p) => {
        const current = new RegExp(`=== ${p.replace(/\./g, "\\.")} ===\\n([\\s\\S]*?)(?=\\n\\n=== |\\n\\nRelated files|$)`).exec(input)?.[1] ?? "";
        if (p.endsWith(".css")) {
          const hex = /#[0-9a-fA-F]{6}/.exec(request)?.[0] ?? "#123456";
          const line = /--bg: #[0-9a-fA-F]{6};/.exec(current)?.[0] ?? "--bg: #0b0b0f;";
          return { path: p, operation: "patch" as const, content: "", patches: [{ search: line, replace: `--bg: ${hex};` }], explanation: "Changed background" };
        }
        const quoted = /["“']([^"”']{1,80})["”']/.exec(request)?.[1] ?? "Updated heading";
        const h1 = /<h1 id="title">[^<]*<\/h1>/.exec(current)?.[0] ?? '<h1 id="title"></h1>';
        return { path: p, operation: "patch" as const, content: "", patches: [{ search: h1, replace: `<h1 id="title">${quoted}</h1>` }], explanation: "Changed heading" };
      });
      return { operations: ops, dependencies: [], validation: [], complete: true };
    }
    case "repair_operations": {
      const ops: unknown[] = [];
      const re = /=== ([^\n]+) ===\n([\s\S]*?)(?=\n\n=== |$)/g;
      let m: RegExpExecArray | null;
      while ((m = re.exec(input))) {
        const [, path, content] = m;
        if (content.includes('import pad from "left-pad";')) {
          ops.push({
            path,
            operation: "patch",
            content: "",
            patches: [
              { search: 'import pad from "left-pad";\n', replace: "const pad = (s, n) => String(s).padStart(n);\n" },
            ],
            explanation: "Replaced unavailable left-pad package with String.prototype.padStart",
          });
        }
      }
      return { operations: ops, dependencies: [], validation: ["Rebuild"], complete: true };
    }
    case "deck_spec":
      return mockDeck(input, request);
    case "scene_spec":
      return mockSceneFor(request);
    case "scene_code":
      return {
        summary: "A glowing ring of orbs slowly turning around a pulsing core.",
        code: [
          "const { THREE, colors, color, speed, density, standard } = ctx;",
          "const group = new THREE.Group();",
          "const core = new THREE.Mesh(new THREE.IcosahedronGeometry(0.9, 1), standard(colors.primary, colors.secondary, { emissiveIntensity: 0.8 }));",
          "group.add(core);",
          "const orbGeo = new THREE.SphereGeometry(0.18, 16, 12);",
          "const orbMat = new THREE.MeshBasicMaterial({ color: color(colors.secondary) });",
          "const orbs = [];",
          "for (let i = 0; i < Math.round(8 + 10 * density); i++) { const m = new THREE.Mesh(orbGeo, orbMat); group.add(m); orbs.push(m); }",
          "const update = (t) => {",
          "  core.scale.setScalar(1 + Math.sin(t * 2 * speed) * 0.08);",
          "  orbs.forEach((m, i) => { const a = (i / orbs.length) * Math.PI * 2 + t * 0.4 * speed; m.position.set(Math.cos(a) * 2.4, Math.sin(a * 2) * 0.3, Math.sin(a) * 2.4); });",
          "};",
          "return { group, update };",
        ].join("\n"),
      };
    case "frame_content":
      return {
        summary: "Hero layout",
        frameFill: "#0f0f12",
        nodes: [
          { type: "text", name: "Headline", x: 48, y: 64, w: 520, h: 72, fill: "transparent", stroke: "transparent", strokeWidth: 0, radius: 0, opacity: 1, text: request.slice(0, 40) || "Headline", fontSize: 48, fontWeight: 700, color: "#ededf0", align: "left" },
          { type: "text", name: "Body", x: 48, y: 150, w: 480, h: 60, fill: "transparent", stroke: "transparent", strokeWidth: 0, radius: 0, opacity: 1, text: "Generated by the Strata test provider.", fontSize: 18, fontWeight: 400, color: "#a1a1aa", align: "left" },
          { type: "rect", name: "Button", x: 48, y: 240, w: 160, h: 44, fill: "#7c8cff", stroke: "transparent", strokeWidth: 0, radius: 10, opacity: 1, text: "", fontSize: 16, fontWeight: 600, color: "#0b0b0f", align: "center" },
        ],
      };
    default:
      throw new AIError("BAD_REQUEST", `mock provider has no fixture for ${schemaName}`);
  }
}
